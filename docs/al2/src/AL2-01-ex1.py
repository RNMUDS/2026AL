# 数当てゲーム: コンピュータが「秘密の数」を当てる
# 1 から 100 までの中に秘密の数が1つある。
# コンピュータは「中央を聞く」作戦で当てにいく。
# 「中央を聞いて、答えによって範囲を半分に減らす」をくり返す方法を
# 二分探索という。前期に習った探索の復習。

# --- 準備: 変数を用意する ---
# 変数 = 値に名前を付けて覚えておく箱。「名前 = 値」の形で作る
secret = 73      # 秘密の数（あとで自由に変えてよい）
low = 1          # 探す範囲の下限（いま「この数以上」と分かっている値）
high = 100       # 探す範囲の上限（いま「この数以下」と分かっている値）
count = 0        # 何回目の質問かを数える。最初は 0 回

# print() は () の中身を画面に表示する命令
print("秘密の数を 1〜100 の中から当てます")
# 文字列 * 数 は、その文字列を数の回数だけくり返してつなげる
# 例 "-" * 3 は "---" になる。ここでは区切り線を 44 個の - で引いている
print("-" * 44)

# --- 二分探索のくり返し ---
# while は「条件が正しいあいだ、中の処理をくり返す」文
# low <= high は「探す範囲がまだ残っている」という意味。
# 範囲がなくなる（low が high を追いこす）と、くり返しが終わる
while low <= high:
    count = count + 1               # 質問の回数を 1 増やす
    # // は「小数を切り捨てる割り算」。例 7 // 2 は 3（3.5 の小数を捨てる）
    # (low + high) // 2 で、範囲の中央の整数が求まる
    middle = (low + high) // 2      # 範囲の中央の整数

    # print では , で区切ると、値のあいだに空白を入れて並べて表示できる
    # end="  " は「最後に改行せず、空白 2 つを付ける」という指定。
    # こうすると、次の print の内容が同じ行の続きに表示される
    print("質問", count, "回目: 範囲", low, "〜", high, "／中央は", middle, end="  ")

    # if / elif / else は「条件によって処理を分ける」文
    # == は「等しいか」を調べる。= （代入）とは別物なので注意
    if middle == secret:
        print("→ 正解！")
        # break は「くり返しをその場でやめて、while の外に出る」命令
        break
    # elif は「上の条件が違ったとき、次にこの条件を調べる」
    elif middle < secret:
        print("→ もっと大きい")
        # 答えは中央より大きいので、中央より左（小さい側）はもう不要。
        # 例 範囲 1〜100 で中央 50 が「もっと大きい」なら、次は 51〜100
        low = middle + 1            # 下限を上げて、右半分だけを残す
    # else は「どの条件にも当てはまらなかったとき」
    else:
        print("→ もっと小さい")
        # 答えは中央より小さいので、中央より右（大きい側）はもう不要。
        # 例 範囲 51〜100 で中央 75 が「もっと小さい」なら、次は 51〜74
        high = middle - 1           # 上限を下げて、左半分だけを残す

# --- 結果の表示 ---
print("-" * 44)
# 100 個の数でも、範囲が半分ずつ減るので 7 回以内に必ず当たる
print("秘密の数", secret, "を", count, "回の質問で当てました")
