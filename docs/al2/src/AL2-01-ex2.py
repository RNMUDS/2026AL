# 後期のテーマ「最適化」の入口
# 学校を出発して3か所を回り、学校へ戻る。いちばん短い順番はどれか。
# 「考えられる順番を全部試して、いちばん良いものを選ぶ」やり方を
# 全探索という。前期に習った探索の復習であり、
# 後期に学ぶ「最適化」のいちばん素朴な方法でもある。

# --- 移動時間の表 ---
# 2地点のあいだの移動時間（分）
# { キー: 値, ... } は辞書。キーから値を引ける表のようなデータ。
# ここではキーが ("学校", "郵便局") のようなタプル（2 つの値の組）、
# 値がその 2 地点のあいだの移動時間（分）。
# 例 travel_time[("学校", "郵便局")] と書くと 9 が取り出せる
travel_time = {
    ("学校", "郵便局"): 9,
    ("学校", "図書館"): 5,
    ("学校", "カフェ"): 8,
    ("郵便局", "図書館"): 6,
    ("郵便局", "カフェ"): 4,
    ("図書館", "カフェ"): 12,
}


# def は「関数を作る」文。() の中の a, b が引数（関数に渡す値の受け取り口）
def minutes_between(a, b):
    """2地点 a と b のあいだの移動時間（分）を返す

    表には ("学校", "郵便局") のように片方向しか書いていないので、
    (a, b) と (b, a) の両方をためす。
    """
    # 辞書の in は「そのキーが辞書にあるか」を調べる
    if (a, b) in travel_time:
        # return は「関数の答えを返して、関数を終える」命令
        return travel_time[(a, b)]      # 辞書[キー] で値を取り出す
    return travel_time[(b, a)]          # 逆向きのキーで取り出す


def total_minutes(route):
    """学校 → route の順に回る → 学校 に戻るまでの合計時間（分）を返す

    route = 回る順番を並べたリスト。例 ["郵便局", "図書館", "カフェ"]
    """
    total = 0                           # 合計時間。最初は 0 分
    place = "学校"                      # いまいる場所。出発は学校
    # for 変数 in リスト: は「リストの要素を先頭から順に取り出してくり返す」文
    # next_place に "郵便局", "図書館", ... と、次に行く場所が順に入る
    for next_place in route:
        # いまの場所から次の場所までの時間を足す
        total = total + minutes_between(place, next_place)
        place = next_place              # 移動したので、いまの場所を更新する
    # 最後の場所から学校までの時間を足す
    # なぜなら、学校 → route の順に回る → 学校 に戻るまでの合計時間を求めたいから
    total = total + minutes_between(place, "学校")
    return total


# --- 回る順番をすべて書き出す ---
# 3か所を回る順番は、全部で 6 通りある。全部書き出して1つずつ試す。
# （最初に 3 通り、次に残り 2 通り、最後は 1 通りなので 3 × 2 × 1 = 6 通り）
# [ [...], [...], ... ] は「リストの中にリストが入った」形。
# all_routes[0] が最初の順番 ["郵便局", "図書館", "カフェ"] になる
all_routes = [
    ["郵便局", "図書館", "カフェ"],
    ["郵便局", "カフェ", "図書館"],
    ["図書館", "郵便局", "カフェ"],
    ["図書館", "カフェ", "郵便局"],
    ["カフェ", "郵便局", "図書館"],
    ["カフェ", "図書館", "郵便局"],
]

print("学校 → 3か所 → 学校 の合計時間をすべて調べる")
print("-" * 52)                     # "-" を 52 個つなげた区切り線

# --- 全探索: 1つずつ試して、いちばん短いものを覚えておく ---
# None は「まだ何もない」を表す特別な値。最初は最短の記録がないので None
best_route = None                   # これまでにいちばん短かった順番
best_time = None                    # そのときの合計時間

for route in all_routes:            # 6 通りの順番を 1 つずつ取り出す
    minutes = total_minutes(route)  # 関数を呼び出して合計時間を計算する
    # " → ".join(リスト) は、リストの要素を " → " でつないだ文字列を作る
    # 例 " → ".join(["a", "b"]) は "a → b"
    print("学校 →", " → ".join(route), "→ 学校 :", minutes, "分")
    # is None は「まだ記録がない（最初の 1 回目）」という条件。
    # or は「どちらか一方でも正しければ正しい」。
    # 最初の 1 回目、または これまでの記録より短いときに、記録を更新する
    if best_time is None or minutes < best_time:
        best_time = minutes
        best_route = route

# --- 結果の表示 ---
print("-" * 52)
print("試した順番の数:", len(all_routes), "通り")
print("いちばん短い順番: 学校 →", " → ".join(best_route), "→ 学校")
print("そのときの合計時間:", best_time, "分")
