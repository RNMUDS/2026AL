# 同じ「探す」でも、やり方によって手数がどれだけ違うかを数える
# 前期に習った2つの探索（逐次探索・二分探索）を関数にして、
# データの個数を増やしながら「何回調べたか」を比べる。


# --- 逐次探索（線形探索） ---
# def は「関数を作る」文。関数 = 処理に名前を付けて、何度でも呼び出せるもの
# 関数名の後ろの () の中が引数（ひきすう）= 関数に渡す値の受け取り口
def linear_search_count(data, target):
    """先頭から1つずつ調べる（逐次探索）。調べた回数を返す

    data   = 探す対象のリスト（小さい順に並んでいなくてもよい）
    target = 探したい値
    """
    count = 0                       # 調べた回数。最初は 0 回
    # for 変数 in リスト: は「リストの要素を先頭から1つずつ取り出して
    # 変数に入れ、中の処理をくり返す」文。value に 1, 2, 3, ... が順に入る
    for value in data:
        count = count + 1           # 1 つ見るたびに回数を 1 増やす
        if value == target:         # 探している値と同じなら
            # return は「関数の答えを返して、関数を終える」命令
            return count            # ここまでに調べた回数を答えとして返す
    return count                    # 最後まで見つからなければ全部の回数を返す


# --- 二分探索 ---
def binary_search_count(data, target):
    """まん中と比べて半分ずつ捨てる（二分探索）。調べた回数を返す

    data   = 小さい順に並んだリスト（並んでいないと正しく動かない）
    target = 探したい値
    """
    # リストの位置（添字）は 0 から始まる。data[0] が先頭の要素
    low = 0                         # 探す範囲の先頭の位置
    # len(data) はリストの要素数。最後の要素の位置は「要素数 - 1」になる
    # 例 要素が 10 個なら、位置は 0〜9 なので最後は 9
    high = len(data) - 1            # 探す範囲の最後の位置
    count = 0                       # 調べた回数
    # while は「条件が正しいあいだ、中の処理をくり返す」文
    # 探す範囲が残っている（low が high を追いこしていない）あいだ続ける
    while low <= high:
        count = count + 1           # まん中を 1 回見るたびに回数を 1 増やす
        # // は小数を切り捨てる割り算。例 9 // 2 は 4
        middle = (low + high) // 2  # 範囲のまん中の位置
        # data[middle] は「リストの middle 番目の要素」を取り出す書き方
        if data[middle] == target:
            return count            # 見つかったので、調べた回数を返す
        elif data[middle] < target:
            # まん中の値が小さすぎる → 答えは右側にある。左半分を捨てる
            low = middle + 1
        else:
            # まん中の値が大きすぎる → 答えは左側にある。右半分を捨てる
            high = middle - 1
    return count                    # 見つからなかったときも回数を返す


# --- データの個数を変えて、2つの探索の回数を比べる ---
# 表の見出し行。文字列の中の空白で、列の位置をそろえている
print("データの個数     逐次探索の回数     二分探索の回数")
print("-" * 50)                     # "-" を 50 個つなげた区切り線

# [10, 100, ...] はリスト。size に 10, 100, 1000, ... が順に入る
for size in [10, 100, 1000, 10000, 100000]:
    # range(a, b) は a から b - 1 までの整数を順に作る（b は含まない）
    # 例 range(1, 4) は 1, 2, 3。list() でそれをリストに変換する
    data = list(range(1, size + 1))   # 1, 2, 3, ... という並んだデータを作る
    target = size                     # いちばん最後の数をさがす
    # 関数名(値, 値) と書くと関数が呼び出され、return した答えが返ってくる
    times_linear = linear_search_count(data, target)
    times_binary = binary_search_count(data, target)
    # f"..." は f文字列。{} の中に変数を書くと、その値が文字列に埋めこまれる
    # {size:>10} は「10 文字分の幅で右そろえ」という表示の指定
    # 例 f"{7:>4}" は "   7"（空白 3 つと 7）になる
    print(f"{size:>10}   {times_linear:>14}   {times_binary:>14}")

print("-" * 50)
# 逐次探索の回数は個数と同じだけ増えるが、
# 二分探索の回数は個数が 10 倍になっても 3〜4 回しか増えない
print("データが10倍になっても、二分探索の回数はほとんど増えない")
